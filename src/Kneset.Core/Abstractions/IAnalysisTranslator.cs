using Kneset.Core.Models;

namespace Kneset.Core.Abstractions;

/// <summary>
/// Переводчик готового анализа на целевой язык. Конвейер: мастер-анализ генерируется
/// один раз (en), переводы делаются лениво по запросу языка — так содержание
/// идентично на всех языках (analysis-policy.md, §6) и дешевле независимых генераций.
/// </summary>
public interface IAnalysisTranslator
{
    /// <param name="sourceDocument">
    /// Оригинал документа, если целевой язык совпадает с языком, на котором
    /// документ написан. Тогда термины восстанавливаются по источнику,
    /// а не переводятся обратно — см. <see cref="AnalysisTranslation"/>.
    /// В остальных случаях null: документ обычно крупнее самого разбора,
    /// и подавать его без нужды значит платить за токены впустую.
    /// </param>
    Task<AnalysisTranslation> TranslateAsync(
        BillAnalysisResult source, string targetLanguage,
        string? sourceDocument = null, CancellationToken ct = default);
}

/// <summary>
/// Перевод и та модель, которая его действительно сделала.
///
/// Отдельно про язык оригинала. Мастер-анализ генерируется на английском,
/// остальные языки получаются переводом мастера — так содержание на всех
/// языках гарантированно одно, чего и требует §6 политики. Но документы
/// Кнессета написаны на иврите, и для иврита выходил круг: документ
/// на иврите → разбор на английском → перевод обратно на иврит. Термины
/// проходили два преобразования и возвращались пересказом: «פסקת ההגבלה»
/// уезжало в «limitation clause» и возвращалось неизвестно чем. Читателю
/// отдавалась чужая формулировка вместо терминов его собственного закона —
/// при том что оригинал у нас есть.
///
/// Поэтому при переводе на язык документа переводчику подаётся сам
/// документ, и он восстанавливает термины по источнику. Правило общее,
/// а не исключение для иврита: язык документа и есть авторитет
/// по терминологии.
///
/// Версия возвращается результатом, а не читается свойством провайдера,
/// намеренно. Прежде интерфейс отдавал <c>ModelVersion</c> отдельно,
/// и составной переводчик (бесплатный до квоты, потом платный) сообщал
/// в нём того, к кому пойдёт СЛЕДУЮЩИМ. В базу попадала запись
/// «gemini-3.5-flash» о переводе, который сделал Claude, — то есть поле
/// происхождения врало. Так эту ошибку нельзя написать снова.
/// </summary>
public record AnalysisTranslation(BillAnalysisResult Analysis, string ModelVersion);
