namespace Kneset.Core.Entities;

/// <summary>
/// Комиссия Кнессета — та, что ведёт законопроект на стадии подготовки.
///
/// Нужна ради одного вопроса, на который платформа до сих пор не отвечала.
/// Бейдж окна влияния говорит «комиссия принимает письменные позиции», но
/// не называет, какая именно: у Кнессета шестнадцать основных комиссий,
/// и позиция по застройке идёт не туда же, куда по образованию. Адрес
/// секретариата в справочнике есть, и он заполнен у всех шестнадцати.
///
/// Идентификатор — из источника, без своего суррогатного: на него ссылается
/// Bill.CommitteeId, и второй ключ здесь ничего не добавил бы.
/// </summary>
public class Committee
{
    /// <summary>CommitteeID из справочника Кнессета.</summary>
    public int Id { get; set; }

    public string Name { get; set; } = "";

    /// <summary>
    /// Почта секретариата: куда человек отправляет письменную позицию.
    /// Может быть пустой у подкомиссий и упразднённых — у основных
    /// комиссий текущего созыва заполнена везде.
    /// </summary>
    public string? Email { get; set; }

    /// <summary>Основная комиссия или подкомиссия — CommitteeTypeID = 71 у основных.</summary>
    public bool IsMain { get; set; }

    public bool IsCurrent { get; set; }

    public DateTime LastUpdatedDate { get; set; }
}
