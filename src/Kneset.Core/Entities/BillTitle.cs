namespace Kneset.Core.Entities;

/// <summary>
/// Название законопроекта на языке интерфейса.
///
/// Оригинал живёт в Bill.Name и остаётся первой строкой везде: название
/// законопроекта в Израиле — формула с юридическим весом, и подменять её
/// машинным переводом нельзя. Перевод идёт под ним, второй строкой.
///
/// Отдельная таблица, а не колонки по языкам: языков четыре сейчас и может
/// стать больше, а строка на язык добавляется без миграции. Существующее поле
/// Bill.NameRu остаётся ради поиска по ключевым словам в уведомлениях —
/// оно заполнялось побочным следствием перевода анализа и по сути пустое.
/// </summary>
public class BillTitle
{
    public int Id { get; set; }

    public int BillId { get; set; }
    public Bill Bill { get; set; } = null!;

    /// <summary>Код языка: ru, en, ar. Иврит не хранится — он в Bill.Name.</summary>
    public string LanguageCode { get; set; } = "";

    public string Text { get; set; } = "";

    /// <summary>
    /// Чем переведено. Нужно, чтобы отличить перевод старой моделью от нового
    /// и при смене провайдера перевести заново, не трогая остальное.
    /// </summary>
    public string ModelVersion { get; set; } = "";

    /// <summary>
    /// Название законопроекта в момент перевода. Кнессет правит названия —
    /// сравнение с текущим Bill.Name показывает, что перевод устарел.
    /// </summary>
    public string SourceName { get; set; } = "";

    public DateTime GeneratedAt { get; set; }
}
