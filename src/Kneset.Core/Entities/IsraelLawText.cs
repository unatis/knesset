namespace Kneset.Core.Entities;

/// <summary>
/// Текст действующего закона — копия сводной редакции из «ספר החוקים הפתוח»
/// (Викитека), на которую ссылается сам Кнессет.
///
/// Почему копия, а не только ссылка: страница закона без текста нечего
/// показывать поисковику и нечего дать разборщику. Со текстом каждая
/// из двух тысяч страниц становится документом, а конвейер разбора,
/// написанный для законопроектов, начинает работать и для законов.
///
/// Почему это законно: законодательные акты авторским правом в Израиле
/// не охраняются, а тексты в Викитеке под свободной лицензией. Атрибуция
/// обязательна и стоит на странице.
///
/// Чего копия стоит: пока мы ссылались, у читателя всегда была последняя
/// версия; как только скопировали — за свежесть отвечаем мы. Поэтому
/// храним номер ревизии и её дату и показываем их рядом с текстом:
/// «сводная редакция такая-то на такое-то число», а не «текст закона».
/// </summary>
public class IsraelLawText
{
    public int Id { get; set; }

    public int IsraelLawId { get; set; }
    public IsraelLaw IsraelLaw { get; set; } = null!;

    /// <summary>Адрес страницы-источника.</summary>
    public string SourceUrl { get; set; } = "";

    /// <summary>Название страницы в Викитеке — по нему запрашивается обновление.</summary>
    public string SourceTitle { get; set; } = "";

    /// <summary>Номер ревизии источника: по нему видно, что текст сменился.</summary>
    public long Revision { get; set; }

    /// <summary>Дата этой ревизии — то, что показываем читателю.</summary>
    public DateTime RevisionAt { get; set; }

    public string Text { get; set; } = "";

    public int CharCount { get; set; }

    /// <summary>Версия чистки викиразметки: сменилась — перечитываем.</summary>
    public string CleanerVersion { get; set; } = "";

    public DateTime FetchedAt { get; set; }
}
