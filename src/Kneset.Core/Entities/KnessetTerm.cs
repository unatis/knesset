namespace Kneset.Core.Entities;

/// <summary>
/// Созыв Кнессета и его границы во времени.
///
/// В API это `KNS_KnessetDates` — по строке на каждую сессию пленума,
/// у 25-го созыва их восемь. Нам нужны не сессии, а границы созыва,
/// поэтому при синхронизации они сворачиваются: начало — самая ранняя
/// сессия, конец — самая поздняя.
///
/// Зачем это в базе. Во-первых, страница расклада должна честно
/// говорить, на какой созыв смотрит читатель и не закончился ли он:
/// 25-й закончился 17 июля 2026, и его состав — уже история.
/// Во-вторых, номер действующего созыва до сих пор выводился как
/// максимум `KnessetNum` по законопроектам, а это догадка, а не факт.
/// </summary>
public class KnessetTerm
{
    /// <summary>Номер созыва. Он же ключ — свой суррогат тут не нужен.</summary>
    public int Id { get; set; }

    /// <summary>Название на иврите, как его отдаёт Кнессет.</summary>
    public string? Name { get; set; }

    /// <summary>Первое заседание пленума.</summary>
    public DateOnly StartDate { get; set; }

    /// <summary>Конец последней сессии. У завершённого созыва — его конец.</summary>
    public DateOnly? FinishDate { get; set; }

    /// <summary>Признак действующего по данным Кнессета.</summary>
    public bool IsCurrent { get; set; }
}
