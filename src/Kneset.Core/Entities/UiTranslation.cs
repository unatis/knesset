namespace Kneset.Core.Entities;

/// <summary>
/// Перевод UI-строки. Основной источник локализации: DbBackedLocalizer читает отсюда
/// (с кэшем), а .resx-файлы служат значениями по умолчанию — сидер импортирует их
/// при старте, недостающие ключи берутся из файлов. Правка перевода в базе
/// не требует пересборки приложения.
/// </summary>
public class UiTranslation
{
    public int Id { get; set; }

    /// <summary>Ключ ресурса (как в .resx), напр. "Nav_Bills".</summary>
    public string Key { get; set; } = "";

    /// <summary>Двухбуквенный код языка: ru / en / he / ar.</summary>
    public string LanguageCode { get; set; } = "";

    public string Value { get; set; } = "";

    /// <summary>
    /// Значение, каким его засеял сидер из .resx. Нужно, чтобы отличить строку,
    /// которую никто не трогал, от отредактированной прямо в базе.
    ///
    /// Без этого правки в .resx не доходили до приложения вообще: сидер добавлял
    /// только отсутствующие пары, а база в локализации приоритетнее файлов —
    /// изменённый текст молча игнорировался, и приходилось заводить ключ-двойник.
    /// Теперь сидер обновляет строку, если Value совпадает с SeededValue
    /// (значит, руками её не меняли), и не трогает, если они разошлись.
    ///
    /// null у строк, засеянных до появления колонки: их разумнее считать
    /// нетронутыми, иначе прежние правки в .resx так и не применятся.
    /// </summary>
    public string? SeededValue { get; set; }

    public DateTime UpdatedAt { get; set; }
}
